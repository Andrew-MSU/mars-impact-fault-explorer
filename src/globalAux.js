    uraniumPpb: v.C_U_BSM,
    thoriumPpb: v.C_Th_BSM,
    potassiumPpm: v.C_K_BSM,
    uraniumMantlePpb: v.C_U_DM,
    thoriumMantlePpb: v.C_Th_DM,
    potassiumMantlePpm: v.C_K_DM,
